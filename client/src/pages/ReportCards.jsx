import { useState, useEffect } from 'react'
import Layout from '../components/Layout'
import { Card, Button, Input, Select, Modal, Alert, EmptyState, SkeletonTable, PageHeader, Badge } from '../components/ui'
import { reportCardAPI, studentAPI, exportAPI } from '../api'
import { useAuthStore } from '../store'
import { FileText, Plus, Download, GraduationCap } from 'lucide-react'

const GRADE_BADGE  = { A: 'success', B: 'info', C: 'warning', D: 'danger' }
const GRADE_LABEL  = { A: 'Excellent', B: 'Good', C: 'Satisfactory', D: 'Needs Improvement' }

export default function ReportCards() {
  const { user } = useAuthStore()
  const isAdmin   = user?.role === 'ADMIN'
  const isTeacher = user?.role === 'TEACHER'
  const isStudent = user?.role === 'STUDENT'
  const isParent  = user?.role === 'PARENT'
  const canGenerate = isAdmin || isTeacher

  const [cards, setCards]       = useState([])
  const [students, setStudents] = useState([])   // for generate dropdown (admin/teacher)
  const [loading, setLoading]   = useState(true)
  const [showModal, setShowModal] = useState(false)
  const [error, setError]       = useState('')
  const [modalError, setModalError] = useState('')
  const [generating, setGenerating] = useState(false)
  const [form, setForm] = useState({ studentId: '', term: '', year: '', teacherRemark: '', principalRemark: '' })

  useEffect(() => {
    fetchCards()
    if (canGenerate) fetchStudents()
  }, [user])

  const fetchCards = async () => {
    try {
      setLoading(true)
      const { data } = await reportCardAPI.getAll()
      setCards(data.data ?? [])
    } catch { setError('Failed to load report cards.') }
    finally { setLoading(false) }
  }

  const fetchStudents = async () => {
    try {
      const { data } = await studentAPI.getAll()
      // backend returns { students, total } shape
      setStudents(data.data?.students ?? data.data ?? [])
    } catch {}
  }

  const handleGenerate = async (e) => {
    e.preventDefault()
    setModalError('')
    setGenerating(true)
    try {
      await reportCardAPI.generate({
        studentId: Number(form.studentId),
        term: form.term,
        year: Number(form.year),
        teacherRemark: form.teacherRemark || undefined,
        principalRemark: form.principalRemark || undefined,
      })
      fetchCards()
      setShowModal(false)
    } catch (err) {
      setModalError(err.response?.data?.message ?? 'Failed to generate report card.')
    } finally {
      setGenerating(false)
    }
  }

  const handleDownload = async (id) => {
    try {
      const res = await exportAPI.reportCardPDF(id)
      const url = URL.createObjectURL(new Blob([res.data], { type: 'application/pdf' }))
      const a = document.createElement('a')
      a.href = url
      a.download = `report-card-${id}.pdf`
      document.body.appendChild(a)
      a.click()
      a.remove()
      URL.revokeObjectURL(url)
    } catch {
      setError('Failed to download PDF. The export service may not be available.')
    }
  }

  return (
    <Layout>
      <div className="space-y-6">
        <PageHeader
          title="Report Cards"
          subtitle={
            isStudent ? 'Your academic term summaries' :
            isParent  ? "Your children's academic summaries" :
            'Generate and manage term report cards'
          }
          actions={canGenerate && (
            <Button onClick={() => { setModalError(''); setForm({ studentId: '', term: '', year: '' }); setShowModal(true) }}>
              <Plus className="w-4 h-4" />Generate Report Card
            </Button>
          )}
        />

        {error && <Alert type="error" onClose={() => setError('')}>{error}</Alert>}

        <Card>
          {loading ? (
            <SkeletonTable rows={5} cols={5} />
          ) : cards.length === 0 ? (
            <EmptyState
              icon={FileText}
              title={isStudent ? 'No report cards yet' : isParent ? 'No report cards available' : 'No report cards yet'}
              description={
                isStudent ? 'Your report cards will appear here once generated by your teacher.' :
                isParent  ? "Your children's report cards will appear here once generated." :
                'Generate a report card by selecting a student, term, and year.'
              }
              action={canGenerate && (
                <Button onClick={() => setShowModal(true)}>
                  <Plus className="w-4 h-4" />Generate Report Card
                </Button>
              )}
            />
          ) : (
            <div className="table-wrapper">
              <table className="data-table">
                <thead>
                  <tr>
                    <th>Student</th>
                    <th>Term</th>
                    <th>Year</th>
                    <th>Grade</th>
                    <th>Remark</th>
                    <th>Download</th>
                  </tr>
                </thead>
                <tbody>
                  {cards.map(c => (
                    <tr key={c.id}>
                      <td>
                        <div className="flex items-center gap-2">
                          <div className="w-7 h-7 rounded-full bg-brand-100 flex items-center justify-center shrink-0">
                            <GraduationCap className="w-3.5 h-3.5 text-brand-600" />
                          </div>
                          <span className="font-medium text-slate-800">
                            {c.student?.fullName ?? `Student #${c.studentId}`}
                          </span>
                        </div>
                      </td>
                      <td><Badge variant="brand">Term {c.term}</Badge></td>
                      <td className="text-slate-500">{c.year}</td>
                      <td>
                        <div className="flex items-center gap-2">
                          <Badge variant={GRADE_BADGE[c.overallGrade] ?? 'gray'}>
                            {c.overallGrade}
                          </Badge>
                          <span className="text-xs text-slate-400 hidden sm:inline">
                            {GRADE_LABEL[c.overallGrade] ?? ''}
                          </span>
                        </div>
                      </td>
                      <td className="text-slate-500 text-sm max-w-[180px] truncate">
                        {c.remark ?? '—'}
                      </td>
                      <td>
                        <button
                          onClick={() => handleDownload(c.id)}
                          className="inline-flex items-center gap-1.5 text-xs font-semibold text-brand-600 hover:text-brand-700 bg-brand-50 hover:bg-brand-100 px-2.5 py-1.5 rounded-lg transition-colors"
                        >
                          <Download className="w-3.5 h-3.5" />
                          PDF
                        </button>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </Card>
      </div>

      {/* Generate modal — admin/teacher only */}
      <Modal
        isOpen={showModal}
        onClose={() => setShowModal(false)}
        title="Generate Report Card"
        actions={[
          <Button key="c" variant="secondary" onClick={() => setShowModal(false)}>Cancel</Button>,
          <Button key="s" onClick={handleGenerate} disabled={generating}>
            {generating ? 'Generating…' : 'Generate'}
          </Button>,
        ]}
      >
        {modalError && <Alert type="error" className="mb-4">{modalError}</Alert>}

        <div className="bg-brand-50 border border-brand-200 rounded-xl px-4 py-3 mb-4 text-sm text-brand-700">
          The system will calculate the overall grade from all CBC assessments recorded for the selected student and term.
        </div>

        <form onSubmit={handleGenerate} className="space-y-4">
          <Select
            label="Student" required
            value={form.studentId}
            onChange={e => setForm({...form, studentId: e.target.value})}
            options={students.map(s => ({ value: s.id, label: `${s.fullName} (${s.admissionNo})` }))}
            placeholder="Select a student…"
          />
          <div className="grid grid-cols-2 gap-4">
            <Select
              label="Term" required
              value={form.term}
              onChange={e => setForm({...form, term: e.target.value})}
              options={[
                {value:'1', label:'Term 1'},
                {value:'2', label:'Term 2'},
                {value:'3', label:'Term 3'},
              ]}
            />
            <Input
              label="Year" required
              type="number"
              value={form.year}
              onChange={e => setForm({...form, year: e.target.value})}
              placeholder="2026"
              min="2020"
              max="2030"
            />
          </div>
          <div className="space-y-1.5">
            <label className="block text-sm font-medium text-slate-700">Teacher's Remark (optional)</label>
            <textarea className="input-field resize-y min-h-[70px]" placeholder="e.g. Excellent progress demonstrated across most learning areas…"
              value={form.teacherRemark} onChange={e => setForm({...form, teacherRemark: e.target.value})} />
          </div>
          <div className="space-y-1.5">
            <label className="block text-sm font-medium text-slate-700">Principal's Remark (optional)</label>
            <textarea className="input-field resize-y min-h-[70px]" placeholder="e.g. Promoted to the next term. Keep up the good work…"
              value={form.principalRemark} onChange={e => setForm({...form, principalRemark: e.target.value})} />
          </div>
        </form>
      </Modal>
    </Layout>
  )
}
